// Install event - cache static assets only (NOT pages)
self.addEventListener('install', (event) => {
  console.log('[SW] Installing service worker...');
  event.waitUntil(
    caches.open(STATIC_CACHE)
      .then((cache) => {
        console.log('[SW] Caching static assets');
        return cache.addAll(STATIC_ASSETS);
      })
      .then(() => {
        console.log('[SW] Static assets cached');
        return self.skipWaiting();
      })
      .catch((err) => {
        console.error('[SW] Failed to cache static assets:', err);
      })
  );
});

// Activate event - clean up old caches (NO automatic page caching)
self.addEventListener('activate', (event) => {
  console.log('[SW] Activating service worker...');
  event.waitUntil(
    caches.keys()
      .then((cacheNames) => {
        return Promise.all(
          cacheNames.map((cacheName) => {
            // Delete old version caches
            if (cacheName.startsWith('kjvstudy-') &&
                cacheName !== STATIC_CACHE &&
                cacheName !== BIBLE_CACHE &&
                cacheName !== PAGE_CACHE) {
              console.log('[SW] Deleting old cache:', cacheName);
              return caches.delete(cacheName);
            }
          })
        );
      })
      .then(() => {
        console.log('[SW] Service worker activated');
        return self.clients.claim();
      })
  );
});

// Background pre-caching - only triggered when user requests it
let cachingInProgress = false;
let cachedCount = 0;
let totalToCache = 0;

async function startBackgroundCaching() {
  if (cachingInProgress) return;
  cachingInProgress = true;
  cachedCount = 0;

  console.log('[SW] Starting background pre-cache of', PAGES_TO_CACHE.length, 'pages...');

  const cache = await caches.open(PAGE_CACHE);

  // Check which pages are already cached
  const uncachedPages = [];
  for (const url of PAGES_TO_CACHE) {
    const cached = await cache.match(url);
    if (!cached) {
      uncachedPages.push(url);
    }
  }

  totalToCache = uncachedPages.length;
  console.log('[SW] Need to cache', totalToCache, 'pages');

  if (totalToCache === 0) {
    notifyClients({ type: 'CACHE_COMPLETE', total: PAGES_TO_CACHE.length });
    cachingInProgress = false;
    return;
  }

  // Cache pages in batches with delay to avoid overwhelming the server
  const BATCH_SIZE = 10;
  const BATCH_DELAY = 500; // 0.5 seconds between batches

  for (let i = 0; i < uncachedPages.length; i += BATCH_SIZE) {
    const batch = uncachedPages.slice(i, i + BATCH_SIZE);

    await Promise.all(
      batch.map(async (url) => {
        try {
          const response = await fetch(url);
          if (response.ok) {
            await cache.put(url, response);
            cachedCount++;
            // Notify clients of progress every 10 pages
            if (cachedCount % 10 === 0 || cachedCount === totalToCache) {
              notifyClients({
                type: 'CACHE_PROGRESS',
                cached: cachedCount,
                total: totalToCache
              });
            }
          }
        } catch (err) {
          console.log('[SW] Failed to cache:', url);
        }
      })
    );

    // Wait between batches
    if (i + BATCH_SIZE < uncachedPages.length) {
      await new Promise(resolve => setTimeout(resolve, BATCH_DELAY));
    }
  }

  console.log('[SW] Background caching complete!', cachedCount, 'pages cached');
  cachingInProgress = false;

  // Notify clients that caching is complete
  notifyClients({ type: 'CACHE_COMPLETE', total: PAGES_TO_CACHE.length });
}

// Notify all clients of caching progress
async function notifyClients(message) {
  const clients = await self.clients.matchAll();
  clients.forEach(client => client.postMessage(message));
}

// Fetch event - serve from cache, fallback to network
self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);

  // Only handle same-origin requests
  if (url.origin !== location.origin) {
    return;
  }

  // Skip non-GET requests
  if (event.request.method !== 'GET') {
    return;
  }

  // Skip API requests (they need fresh data)
  if (url.pathname.startsWith('/api/')) {
    // For API requests, try network first, then cache for offline
    event.respondWith(
      fetch(event.request)
        .then((response) => {
          // Cache successful API responses for offline use
          if (response.ok) {
            const responseClone = response.clone();
            caches.open(PAGE_CACHE).then((cache) => {
              cache.put(event.request, responseClone);
            });
          }
          return response;
        })
        .catch(() => {
          // Offline - try to serve from cache
          return caches.match(event.request);
        })
    );
    return;
  }

  // Static assets - cache first
  if (url.pathname.startsWith('/static/')) {
    event.respondWith(
      caches.match(event.request)
        .then((cachedResponse) => {
          if (cachedResponse) {
            return cachedResponse;
          }
          return fetch(event.request).then((response) => {
            if (response.ok) {
              const responseClone = response.clone();
              caches.open(STATIC_CACHE).then((cache) => {
                cache.put(event.request, responseClone);
              });
            }
            return response;
          });
        })
    );
    return;
  }

  // Bible pages (book, chapter, verse) - network first, cache fallback
  if (url.pathname.startsWith('/book/')) {
    event.respondWith(
      fetch(event.request)
        .then((response) => {
          if (response.ok) {
            const responseClone = response.clone();
            caches.open(PAGE_CACHE).then((cache) => {
              cache.put(event.request, responseClone);
            });
          }
          return response;
        })
        .catch(() => {
          return caches.match(event.request).then((cachedResponse) => {
            if (cachedResponse) {
              return cachedResponse;
            }
            // Redirect to offline reader with book/chapter info
            const pathMatch = url.pathname.match(/\/book\/([^\/]+)(?:\/chapter\/(\d+))?/);
            if (pathMatch) {
              const book = decodeURIComponent(pathMatch[1]);
              const chapter = pathMatch[2] || '1';
              return Response.redirect('/offline?book=' + encodeURIComponent(book) + '&chapter=' + chapter, 302);
            }
            return caches.match('/offline');
          });
        })
    );
    return;
  }

  // Other pages - network first with cache fallback
  event.respondWith(
    fetch(event.request)
      .then((response) => {
        if (response.ok) {
          const responseClone = response.clone();
          caches.open(PAGE_CACHE).then((cache) => {
            cache.put(event.request, responseClone);
          });
        }
        return response;
      })
      .catch(() => {
        return caches.match(event.request).then((cachedResponse) => {
          if (cachedResponse) {
            return cachedResponse;
          }
          // For HTML pages, return the cached homepage as fallback
          if (event.request.headers.get('Accept')?.includes('text/html')) {
            return caches.match('/');
          }
        });
      })
  );
});

// Handle messages from the main thread
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }

  // START_CACHING - triggered from /offline page
  if (event.data && event.data.type === 'START_CACHING') {
    console.log('[SW] Received START_CACHING request');
    startBackgroundCaching();
  }

  // Pre-cache specific book/chapter on demand
  if (event.data && event.data.type === 'CACHE_CHAPTER') {
    const { book, chapter } = event.data;
    const url = `/book/${encodeURIComponent(book)}/chapter/${chapter}`;
    caches.open(PAGE_CACHE).then((cache) => {
      fetch(url).then((response) => {
        if (response.ok) {
          cache.put(url, response);
        }
      });
    });
  }
});

